-- 县域分析单元 = 全部区县 + 东莞/中山市本级。
-- 先把省级/地级市重置为 0，再按规则置 1，保证重复执行结果一致。
UPDATE dim_region
SET is_analysis_unit = 0
WHERE region_level IN (1, 2)
  AND region_code NOT IN ('441900', '442000');

UPDATE dim_region
SET is_analysis_unit = 1
WHERE region_level = 3
   OR region_code IN ('441900', '442000');

